function rec(
  partial: Omit<MaintenanceRecord, "photos" | "sessions" | "technicians" | "totalHours" | "startTime" | "endTime"> & {
    technicians?: string[];
    startTime?: string;
    endTime?: string;
    totalHours?: number;
    sessions?: MaintenanceRecord["sessions"];
  },
): MaintenanceRecord {
  const startTime = partial.startTime ?? "08:00";
  const endTime = partial.endTime ?? "17:00";
  const techniciansFinal = partial.technicians ?? [];
  return {
    ...partial,
    technicians: techniciansFinal,
    startTime,
    endTime,
    totalHours: partial.totalHours ?? partial.hours,
    photos: [],
    sessions: partial.sessions ?? [
      {
        date: partial.date,
        startTime,
        endTime,
        hours: partial.hours,
        technicians: techniciansFinal,
        photos: [],
      },
    ],
  };
}

